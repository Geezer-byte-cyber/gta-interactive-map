-- The Knox Map: account markers, customer order portal, orders and hidden recipes
-- Safe to run more than once.

-- Visual account marker. This does not grant any permissions.
ALTER TABLE public.user_profiles
  ADD COLUMN IF NOT EXISTS account_type TEXT NOT NULL DEFAULT 'knox';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'user_profiles_account_type_check'
      AND conrelid = 'public.user_profiles'::regclass
  ) THEN
    ALTER TABLE public.user_profiles
      ADD CONSTRAINT user_profiles_account_type_check
      CHECK (account_type IN ('knox', 'customer'));
  END IF;
END $$;

-- Explicit module permissions. Account markers never grant these.
ALTER TABLE public.user_module_permissions
  ADD COLUMN IF NOT EXISTS can_view_hidden_recipes BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS can_view_orders BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS can_create_orders BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS can_edit_orders BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS can_delete_orders BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS can_manage_customers BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS can_view_own_orders BOOLEAN NOT NULL DEFAULT FALSE;

-- Hidden crafting recipes.
ALTER TABLE public.crafting_recipes
  ADD COLUMN IF NOT EXISTS is_hidden BOOLEAN NOT NULL DEFAULT FALSE;

DROP POLICY IF EXISTS "Hidden recipe visibility gate" ON public.crafting_recipes;
CREATE POLICY "Hidden recipe visibility gate"
ON public.crafting_recipes AS RESTRICTIVE FOR SELECT TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.user_profiles
    WHERE user_id = auth.uid() AND role = 'owner'
  )
  OR (
    is_hidden = FALSE
    AND EXISTS (
      SELECT 1 FROM public.user_module_permissions
      WHERE user_id = auth.uid() AND can_view_crafting = TRUE
    )
  )
  OR (
    is_hidden = TRUE
    AND EXISTS (
      SELECT 1 FROM public.user_module_permissions
      WHERE user_id = auth.uid()
        AND can_view_crafting = TRUE
        AND can_view_hidden_recipes = TRUE
    )
  )
);

DROP POLICY IF EXISTS "Hidden recipe insert permission gate" ON public.crafting_recipes;
CREATE POLICY "Hidden recipe insert permission gate"
ON public.crafting_recipes AS RESTRICTIVE FOR INSERT TO authenticated
WITH CHECK (
  is_hidden = FALSE
  OR EXISTS (
    SELECT 1 FROM public.user_profiles
    WHERE user_id = auth.uid() AND role = 'owner'
  )
  OR EXISTS (
    SELECT 1 FROM public.user_module_permissions
    WHERE user_id = auth.uid()
      AND can_view_crafting = TRUE
      AND can_view_hidden_recipes = TRUE
  )
);

DROP POLICY IF EXISTS "Hidden recipe update permission gate" ON public.crafting_recipes;
CREATE POLICY "Hidden recipe update permission gate"
ON public.crafting_recipes AS RESTRICTIVE FOR UPDATE TO authenticated
USING (
  is_hidden = FALSE
  OR EXISTS (
    SELECT 1 FROM public.user_profiles
    WHERE user_id = auth.uid() AND role = 'owner'
  )
  OR EXISTS (
    SELECT 1 FROM public.user_module_permissions
    WHERE user_id = auth.uid()
      AND can_view_crafting = TRUE
      AND can_view_hidden_recipes = TRUE
  )
)
WITH CHECK (
  is_hidden = FALSE
  OR EXISTS (
    SELECT 1 FROM public.user_profiles
    WHERE user_id = auth.uid() AND role = 'owner'
  )
  OR EXISTS (
    SELECT 1 FROM public.user_module_permissions
    WHERE user_id = auth.uid()
      AND can_view_crafting = TRUE
      AND can_view_hidden_recipes = TRUE
  )
);

-- Order tickets. order_number is the stable KX-000001 style ticket number.
CREATE TABLE IF NOT EXISTS public.orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'New'
    CHECK (status IN ('New', 'In Progress', 'Waiting', 'Completed', 'Cancelled')),
  items JSONB NOT NULL DEFAULT '[]'::jsonb
    CHECK (jsonb_typeof(items) = 'array'),
  customer_user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS orders_customer_user_id_idx
  ON public.orders(customer_user_id);
CREATE INDEX IF NOT EXISTS orders_status_idx
  ON public.orders(status);

CREATE OR REPLACE FUNCTION public.set_orders_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS orders_set_updated_at ON public.orders;
CREATE TRIGGER orders_set_updated_at
BEFORE UPDATE ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.set_orders_updated_at();

-- Internal staff-only notes are deliberately stored separately from customer-visible orders.
CREATE TABLE IF NOT EXISTS public.order_internal_notes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id UUID NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  note TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS order_internal_notes_order_id_idx
  ON public.order_internal_notes(order_id);

ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_internal_notes ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.orders TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.order_internal_notes TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.orders_order_number_seq TO authenticated;

